// 91 공문 다듬이: 날짜·요일·시간·금액(한글 병기)·쌍점 변환 정답값, 항목 기호 순서·들여쓰기, 끝 표시·붙임 표기, 모두 고치기·되돌리기·한 건 고치기·저장
const g = window.__gc;
assert(g, '__gc 가 있어야 함');
const cv = s => g.convert(s);
const eq = (a, b, m) => assert(a === b, m + ': ' + JSON.stringify(a) + ' (기대 ' + JSON.stringify(b) + ')');
// 1) 날짜
eq(cv('2026-11-08'), '2026. 11. 8.', '하이픈 날짜');
eq(cv('2026.11.8'), '2026. 11. 8.', '붙여 쓴 온점 날짜');
eq(cv('2026년 11월 8일'), '2026. 11. 8.', '한글 날짜');
eq(cv('2026/11/08 행사'), '2026. 11. 8. 행사', '빗금 날짜');
eq(cv('2026년 11월 8일(일요일)'), '2026. 11. 8.(일)', '요일 한 글자');
eq(cv('2026. 11. 8.(월)'), '2026. 11. 8.(일)', '틀린 요일 바로잡기');
eq(cv('11월 18일(수요일)까지'), '11. 18.(수)까지', '연도 없는 날짜');
eq(cv('2026. 11. 8.'), '2026. 11. 8.', '이미 맞는 날짜는 그대로');
eq(cv('2026. 2. 30.'), '2026. 2. 30.', '없는 날짜는 건드리지 않음');
// 2) 시간
eq(cv('오후 2시'), '14:00', '오후 2시');
eq(cv('오전 9시 30분'), '09:30', '오전 9시 30분');
eq(cv('오후 12시'), '12:00', '정오');
eq(cv('오전 12시'), '00:00', '자정');
eq(cv('15시 20분'), '15:20', '24시각');
eq(cv('오후 2시~4시 30분'), '14:00~16:30', '시간 범위(오후 이어받기)');
eq(cv('오후 3시 반'), '15:30', '반');
eq(cv('9:05 시작'), '09:05 시작', '두 자리 시');
eq(cv('1시간 동안 4교시'), '1시간 동안 4교시', '시간·교시는 그대로');
// 3) 금액
eq(cv('123,000원'), '금123,000원(금일십이만삼천원)', '금액 한글 병기');
eq(cv('150000원'), '금150,000원(금일십오만원)', '쉼표 없는 금액');
eq(cv('5만원'), '금50,000원(금오만원)', '만원');
eq(cv('금1,000원(금천원)'), '금1,000원(금일천원)', '한글 병기 바로잡기');
eq(cv('금113,560원(금일십일만삼천오백육십원)'), '금113,560원(금일십일만삼천오백육십원)', '맞는 금액은 그대로');
eq(cv('54,000원(부가세포함)'), '금54,000원(금오만사천원)(부가세포함)', '괄호 설명은 남김');
eq(g.korMoney(100010000), '일억일만', '일억일만');
eq(g.korMoney(1203040), '일백이십만삼천사십', '일백이십만삼천사십');
// 4) 쌍점
eq(cv('관련 :교육청'), '관련: 교육청', '쌍점 띄어쓰기');
eq(cv('일시: 14:00'), '일시: 14:00', '맞는 쌍점·시각 그대로');
// 5) 샘플 전체 점검 → 모두 고치기 정답
const src = $('#src');
const cats = g.check(src.value).map(f => f.cat);
for (const c of ['date', 'time', 'money', 'item', 'end', 'att', 'colon']) assert(cats.includes(c), '샘플에 ' + c + ' 문제가 있어야 함: ' + cats.join(','));
assert($$('#preview mark').length === cats.length && $$('#issues .iss').length === cats.length, '강조·목록 수 = 문제 수 ' + cats.length);
assert($('#fixAll').textContent.includes(String(cats.length)), '모두 고치기 버튼에 건수: ' + $('#fixAll').textContent);
const before = src.value;
const EXPECT = [
  '수신  수신자 참조',
  '(경유)',
  '제목  2026학년도 학부모 공개수업 안내',
  '',
  '1. 관련: 햇살초등학교-1234(2026. 10. 20.)',
  '2. 우리 학교 학부모 공개수업을 다음과 같이 실시하오니 참석하여 주시기 바랍니다.',
  '  가. 일시: 2026. 11. 18.(수) 14:00~15:30',
  '  나. 장소: 각 학년 교실 및 강당',
  '  다. 준비물 구입비: 금150,000원(금일십오만원)',
  '    1) 다과비 금120,000원(금일십이만원)',
  '    2) 인쇄비 금30,000원(금삼만원)',
  '  라. 문의: 교무실(054-000-0000)',
  '',
  '붙임  1. 공개수업 시간표 1부.',
  '      2. 참관록 양식 1부.  끝.'].join('\n');
$('#fixAll').click();
await wait(50);
eq(src.value, EXPECT, '모두 고치기 결과');
assert(g.check(src.value).length === 0 && /문제가 없어요/.test($('#issues').textContent), '고친 뒤 문제 0');
// 되돌리기
$('#undo').click();
eq(src.value, before, '되돌리기');
// 6) 항목·끝 규칙 단독
const fx = s => g.fixAll(s);
eq(fx('1. 목적\n1) 안전\n2. 방침'), '1. 목적\n  가. 안전\n2. 방침  끝.', '단계 건너뜀 → 가. 로, 끝 표시 추가');
eq(fx('1. 가\n3. 나\n    가. 다\n    다. 라\n끝'), '1. 가\n2. 나\n  가. 다\n  나. 라  끝.', '번호 순서·들여쓰기·따로 쓴 끝');
eq(fx('바랍니다. 끝.'), '바랍니다.  끝.', '끝 앞 2타');
eq(fx('본문입니다.  끝.\n\n첨부: 계획서 1부'), '본문입니다.\n\n붙임  계획서 1부.  끝.', '붙임이 있으면 끝은 붙임 뒤, 첨부 → 붙임');
eq(fx('본문.\n\n붙임  안내장'), '본문.\n\n붙임  안내장 1부.  끝.', '수량 없으면 1부.');
// 7) 한 건만 고치기
src.value = '일시: 2026-11-08  끝.'; fire(src, 'input');
assert($$('#issues .iss').length === 1, '한 건: ' + $('#issues').textContent);
$('#issues .iss button').click();
eq(src.value, '일시: 2026. 11. 8.  끝.', '한 건 고치기');
// 미리보기는 이스케이프
src.value = '<b>굵게</b> 2026-11-08'; fire(src, 'input');
assert(!$('#preview b') && $('#preview').textContent.startsWith('<b>'), '미리보기 이스케이프');
// 8) 저장
src.value = '저장 확인 2026.1.2'; fire(src, 'input');
await wait(500);
const st = JSON.parse(localStorage.getItem('edu-expo.gongmun-check.v1') || 'null');
assert(st && st.txt === '저장 확인 2026.1.2', '저장: ' + JSON.stringify(st));
return 'ok 8';
